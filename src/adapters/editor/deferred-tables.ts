import type { Node as ProseNode } from '@milkdown/kit/prose/model'
import type { NodeView } from '@milkdown/kit/prose/view'

import { planTableDeferral } from '../../domain/index.js'
import type { MarkdownTableSpan } from '../../domain/index.js'

/** A private code-fence language used only inside the live editor document. */
export const DEFERRED_TABLE_LANGUAGE = 'simplemark-deferred-table'

const MARKER_PREFIX = 'simplemark-deferred-table-v1:'

export interface DeferredTable {
  readonly id: string
  readonly source: string
  readonly rowCount: number
  readonly columnCount: number
  readonly cellCount: number
}

export interface PreparedMarkdown {
  /** Safe Markdown handed to Milkdown. It contains tiny marker fences only. */
  readonly editorMarkdown: string
  readonly deferredTables: ReadonlyMap<string, DeferredTable>
  /** Restores untouched deferred-table source before a session is updated. */
  restoreMarkdown(markdown: string): string
}

function markerFor(id: string): string {
  return `${MARKER_PREFIX}${id}`
}

function placeholderFor(id: string): string {
  // Fenced blocks can interrupt a paragraph in CommonMark, so no synthetic
  // surrounding whitespace is required. Keeping the replacement boundary
  // exact lets an untouched editor projection restore byte-for-byte.
  return `\`\`\`${DEFERRED_TABLE_LANGUAGE}\n${markerFor(id)}\n\`\`\``
}

function deferredTable(id: string, source: string, span: MarkdownTableSpan): DeferredTable {
  return {
    id,
    source,
    rowCount: span.rowCount,
    columnCount: span.columnCount,
    cellCount: span.cellCount,
  }
}

/**
 * Replaces only the tables that exceed the document-wide live-node budget.
 *
 * The real Markdown stays in a per-editor map rather than in the DOM. A
 * rebuild therefore cannot create tens of thousands of editable table-cell
 * nodes, while a normal save writes the exact original source back through the
 * DocumentSession.
 */
export function prepareMarkdownForEditor(markdown: string): PreparedMarkdown {
  const plan = planTableDeferral(markdown)
  if (plan.deferredTables.length === 0) {
    return {
      editorMarkdown: markdown,
      deferredTables: new Map(),
      restoreMarkdown: (next) => next,
    }
  }

  const deferredTables = new Map<string, DeferredTable>()
  const output: string[] = []
  let sourceOffset = 0

  plan.deferredTables.forEach((span, index) => {
    const id = `table-${index}-${span.start}-${span.end}`
    const source = markdown.slice(span.start, span.end)
    deferredTables.set(id, deferredTable(id, source, span))
    output.push(markdown.slice(sourceOffset, span.start), placeholderFor(id))
    sourceOffset = span.end
  })
  output.push(markdown.slice(sourceOffset))

  // Milkdown normally emits backtick fences, but accepting tilde fences too
  // makes this resilient to any future serializer preference. Replacements are
  // exact markers generated by this adapter, never arbitrary user code blocks.
  const placeholderPattern = /(^|\n)(`{3,}|~{3,})simplemark-deferred-table[^\n]*\n(simplemark-deferred-table-v1:[a-z0-9-]+)\n\2(?=\n|$)/g
  return {
    editorMarkdown: output.join(''),
    deferredTables,
    restoreMarkdown: (next) => next.replace(placeholderPattern, (whole, lineStart: string, _fence: string, marker: string) => {
      const id = marker.slice(MARKER_PREFIX.length)
      const table = deferredTables.get(id)
      return table === undefined ? whole : `${lineStart}${table.source}`
    }),
  }
}

function tableForNode(node: ProseNode, tables: ReadonlyMap<string, DeferredTable>): DeferredTable | undefined {
  const marker = node.textContent.trim()
  if (!marker.startsWith(MARKER_PREFIX)) return undefined
  return tables.get(marker.slice(MARKER_PREFIX.length))
}

export function isDeferredTableNode(
  node: ProseNode,
  tables: ReadonlyMap<string, DeferredTable>,
): boolean {
  return tableForNode(node, tables) !== undefined
}

/**
 * Small, non-editable presentation for a table that would otherwise make the
 * initial ProseMirror mount unresponsive. The source never enters this view's
 * DOM; the explicit copy action is the escape hatch for a large-table edit.
 */
export class DeferredTableNodeView implements NodeView {
  readonly dom: HTMLElement
  #table: DeferredTable | undefined
  readonly #tables: ReadonlyMap<string, DeferredTable>
  readonly #copyButton: HTMLButtonElement

  #detailText(): string {
    if (this.#table === undefined) return 'This table is held in safe rendering mode.'
    const rows = this.#table.rowCount.toLocaleString()
    const columns = this.#table.columnCount.toLocaleString()
    const cells = this.#table.cellCount.toLocaleString()
    return `${rows} rows × ${columns} columns (${cells} cells)`
  }

  async #copySource(): Promise<void> {
    if (this.#table === undefined || !navigator.clipboard?.writeText) {
      this.#copyButton.textContent = 'Copy unavailable'
      return
    }
    try {
      await navigator.clipboard.writeText(this.#table.source)
      this.#copyButton.textContent = 'Copied table Markdown'
    } catch {
      this.#copyButton.textContent = 'Copy unavailable'
    }
  }

  update(node: ProseNode): boolean {
    const next = tableForNode(node, this.#tables)
    if (next === undefined) return false
    this.#table = next
    return true
  }

  /** Buttons belong to the safe-renderer card, not ProseMirror. */
  stopEvent(event: Event): boolean {
    return this.dom.contains(event.target as Node)
  }

  /** No editable source is mounted inside this NodeView. */
  ignoreMutation(): boolean {
    return true
  }

  constructor(node: ProseNode, tables: ReadonlyMap<string, DeferredTable>) {
    this.#tables = tables
    this.#table = tableForNode(node, this.#tables)
    this.dom = document.createElement('section')
    this.dom.className = 'deferred-table'
    this.dom.contentEditable = 'false'
    this.dom.setAttribute('data-deferred-table', '')

    const label = document.createElement('h3')
    label.textContent = 'Large table held safely'

    const detail = document.createElement('p')
    detail.className = 'deferred-table-detail'
    detail.textContent = this.#detailText()

    const explanation = document.createElement('p')
    explanation.className = 'deferred-table-explanation'
    explanation.textContent = 'The original Markdown is still in this document and will save unchanged. It was not expanded into thousands of live editing cells.'

    this.#copyButton = document.createElement('button')
    this.#copyButton.type = 'button'
    this.#copyButton.className = 'deferred-table-copy'
    this.#copyButton.textContent = 'Copy table Markdown'
    this.#copyButton.addEventListener('click', () => void this.#copySource())

    this.dom.append(label, detail, explanation, this.#copyButton)
  }
}
